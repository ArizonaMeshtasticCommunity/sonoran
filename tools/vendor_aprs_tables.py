"""Build the APRS name tables the RF tab reads.

The RF tab shows an APRS station the way a person reads it: "Digipeater",
not `/#`; "Microsat WX3in1 Plus 2.0", not `APMI06`. Both names come from
lists that aprs.fi maintains, and this turns them into one small script,
`web/static/vendor/aprs/aprs-tables.js`, which sets
`window.SonoranAprsTables` before `rf.js` runs.

The inputs are files, never fetched here, so a build never depends on
the network and every change to the tables is a reviewed commit:

    gh api repos/hessu/aprs-symbol-index/contents/generated/symbols.dense.json \
        -q .content | base64 -d > symbols.dense.json
    gh api repos/aprsorg/aprs-deviceid/contents/tocalls.yaml \
        -q .content | base64 -d > tocalls.yaml
    uv run python tools/vendor_aprs_tables.py symbols.dense.json tocalls.yaml

Then record the two commits in the directory's PROVENANCE.md. Both lists
are CC BY-SA and ask to be credited, which PROVENANCE.md and the RF tab
do.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

OUT = Path(__file__).resolve().parents[1] / "src/sonoran/web/static/vendor/aprs/aprs-tables.js"

HEADER = """\
/*
 * APRS symbol and device names, for the RF tab. Generated by
 * tools/vendor_aprs_tables.py; do not edit by hand. See PROVENANCE.md.
 *
 * Symbols: the APRS symbol index by Hessu, OH7LZB, for aprs.fi,
 * CC BY-SA 4.0. Devices: the APRS device identification list by Hessu,
 * OH7LZB, for aprs.fi, CC BY-SA 2.0.
 */
"""


def symbols(index: dict[str, Any]) -> dict[str, str]:
    """Return symbol code to name, leaving out codes with no meaning."""
    return {
        code: entry["description"]
        for code, entry in sorted(index["symbols"].items())
        if entry.get("description") and not entry.get("unused")
    }


def device_name(entry: dict[str, Any]) -> str:
    """Name a device the way aprs.fi does: vendor, model, version."""
    parts = [str(entry[key]) for key in ("vendor", "model", "version") if entry.get(key)]
    named: list[str] = []
    for part in parts:
        # The list names some catch-all codes "Unknown"; that is no name.
        # A model that repeats its vendor ("OpenGD77 OpenGD77") says it once.
        if part.lower() != "unknown" and (not named or named[-1] != part):
            named.append(part)
    return " ".join(named)


def specificity(pattern: str) -> tuple[int, int]:
    """Sort key: exact codes first, then fewer wildcards, then longer.

    `*` matches any run, so one of them is broader than any number of
    single-character wildcards, and it sorts after them.
    """
    single = pattern.count("?") + pattern.count("n")
    return (single + 100 * pattern.count("*"), -len(pattern))


def tocalls(listing: dict[str, Any]) -> list[list[str]]:
    """Return [pattern, name] pairs, the most specific pattern first.

    The destination of a plain APRS packet names the software or radio
    that sent it. `?` stands for any character, `n` for a digit and `*`
    for any run; the page matches in this order and takes the first.
    """
    pairs = []
    for entry in listing.get("tocalls", []):
        name = device_name(entry)
        if entry.get("tocall") and name:
            pairs.append([str(entry["tocall"]), name])
    return sorted(pairs, key=lambda pair: (specificity(pair[0]), pair[0]))


def build(index: dict[str, Any], listing: dict[str, Any]) -> str:
    tables = {"symbols": symbols(index), "tocalls": tocalls(listing)}
    body = json.dumps(tables, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    return f"{HEADER}window.SonoranAprsTables = {body};\n"


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    index = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    listing = yaml.safe_load(Path(argv[2]).read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(index, listing), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
