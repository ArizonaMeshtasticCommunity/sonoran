/*
 * ESLint for the hand-written frontend (#248).
 *
 * One rule matters: `no-undef`. `node --check` parses a file and does no
 * scope analysis, so a reference to a name that was deleted passes it and
 * throws in the reader's browser. Six of those were caught during one
 * session's work, by an e2e console check, by running a file in a sandbox,
 * and by a person remembering to grep for a variable's name as well as its
 * attribute. Nothing caught them structurally. This does.
 *
 * NO BUILD STEP. The frontend is plain `<script>` tags on purpose. ESLint is
 * a check that runs in CI and never touches what is served.
 *
 * THE HARD PART: the classic scripts share one global scope. `gaps.js` calls
 * `$` and `el`, which `app.js` declares at its top level. ESLint lints one
 * file at a time and cannot know that.
 *
 * The obvious answer is a hand-kept list of globals, and it is the wrong
 * one. A list is exactly the thing that goes stale when a declaration is
 * deleted: the name stays on the list, and the stale reference it was meant
 * to catch is waved through. So the list is DERIVED here, on every run, from
 * the top-level declarations the scripts actually contain. Delete a function
 * and it leaves the list in the same commit, and every remaining caller in
 * every other file fails. That is the one case this exists for.
 *
 * The derivation reads the source's own top level: a declaration at column
 * zero. That matches how every file here is written, and a nested
 * declaration is correctly not global.
 */
import fs from 'node:fs';
import path from 'node:path';
import globals from 'globals';

const STATIC = 'src/sonoran/web/static';

// Generated or vendored. Not ours to lint, and not ours to fix.
const NOT_OURS = new Set([
  'meshtastic-serial-proto.js', // generated descriptor
  'meshtastic-static.js', // generated by pbjs
  'protobuf-runtime.js', // wraps the vendored runtime
]);

const read = (file) => fs.readFileSync(path.join(STATIC, file), 'utf8');
const isModule = (source) => /^(?:import|export)\s/m.test(source);

const ours = fs
  .readdirSync(STATIC)
  .filter((f) => f.endsWith('.js') && !NOT_OURS.has(f));

// The two workers run in their own global scope, never the page's. Their
// top-level names must not join the shared list below.
const WORKERS = new Set(['planner.worker.js', 'sw.js']);
const scripts = ours.filter((f) => !WORKERS.has(f) && !isModule(read(f)));
const modules = ours.filter((f) => !WORKERS.has(f) && isModule(read(f)));

/*
 * Every name a classic script puts in the shared global scope.
 *
 * `window.X = …` at the top level is how the IIFE modules (units.js,
 * settings.js, preset.js, …) publish themselves.
 */
const TOP_LEVEL = [
  /^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)/gm,
  /^(?:const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm,
  /*
   * `window.X = …` at ANY depth. The IIFE modules publish from inside their
   * own function (`window.SonoranLabels = {` sits two spaces in), and that is
   * exactly how they become global. Missing it made every caller of
   * `SonoranLabels` look undefined on the first run.
   */
  /^\s*window\.([A-Za-z_$][\w$]*)\s*=/gm,
];
/*
 * `const { a, b: c, d = 1 } = …` at the top level declares a, c and d.
 * app.js takes `roleLabel` this way, and planner.js calls it -- see the note
 * in planner.js on why that call no longer relies on app.js.
 */
const DESTRUCTURED = /^(?:const|let|var)\s*\{([^}]*)\}\s*=/gm;
const shared = {};
for (const file of scripts) {
  const source = read(file);
  for (const pattern of TOP_LEVEL) {
    for (const match of source.matchAll(pattern)) shared[match[1]] = 'readonly';
  }
  for (const match of source.matchAll(DESTRUCTURED)) {
    for (const part of match[1].split(',')) {
      const name = part.split(':').pop().split('=')[0].trim();
      if (/^[A-Za-z_$][\w$]*$/.test(name)) shared[name] = 'readonly';
    }
  }
}

/*
 * The vendored libraries, by the global each one defines. Listed rather than
 * derived because they are minified and not ours; there are four and they
 * change only when the vendored copy does.
 */
const vendored = {
  L: 'readonly', // leaflet
  echarts: 'readonly',
  protobuf: 'readonly',
  jsyaml: 'readonly',
};

const rules = {
  'no-undef': 'error',
};

export default [
  {
    // Vendored and generated code is not ours to lint or to fix.
    ignores: [
      `${STATIC}/vendor/**`,
      ...[...NOT_OURS].map((f) => `${STATIC}/${f}`),
    ],
  },
  {
    // Several files carry directives for rules this config does not enable.
    // Reporting those as problems would be noise about someone else's setup.
    linterOptions: { reportUnusedDisableDirectives: 'off' },
  },
  {
    files: scripts.map((f) => `${STATIC}/${f}`),
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'script',
      globals: { ...globals.browser, ...vendored, ...shared },
    },
    rules,
  },
  {
    files: modules.map((f) => `${STATIC}/${f}`),
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'module',
      // A module sees the page's globals through `window`, and a few read
      // the shared helpers directly, so they get the same derived set.
      globals: { ...globals.browser, ...vendored, ...shared },
    },
    rules,
  },
  {
    // A module worker: it imports, and it has worker globals, not window.
    files: [`${STATIC}/planner.worker.js`],
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'module',
      globals: { ...globals.worker },
    },
    rules,
  },
  {
    // The service worker (#322): a classic script with service worker
    // globals (`self`, `caches`, `clients`), and no window.
    files: [`${STATIC}/sw.js`],
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'script',
      globals: { ...globals.serviceworker },
    },
    rules,
  },
];
